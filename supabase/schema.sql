create table if not exists public.events (
  id bigint generated by default as identity primary key,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  severity text not null check (severity in ('low', 'medium', 'high')),
  timestamp timestamptz not null,
  event_type text not null check (event_type in ('pothole', 'speed_bump', 'rough_road')),
  simulated boolean not null default false
);

create table if not exists public.community_reports (
  id uuid primary key,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  severity text not null check (severity in ('low', 'medium', 'high')),
  description text check (description is null or char_length(description) <= 500),
  photo_key text not null unique,
  created_at timestamptz not null,
  source text not null default 'community' check (source = 'community'),
  status text not null default 'unverified' check (status = 'unverified')
);

create table if not exists public.device_events (
  event_id uuid primary key,
  device_id text not null check (char_length(device_id) between 1 and 80),
  timestamp timestamptz not null,
  latitude double precision check (latitude is null or latitude between -90 and 90),
  longitude double precision check (longitude is null or longitude between -180 and 180),
  sensor_summary text not null check (char_length(sensor_summary) between 1 and 500),
  severity text check (severity is null or severity in ('low', 'medium', 'high')),
  event_type text check (event_type is null or event_type in ('pothole', 'speed_bump', 'rough_road')),
  impact_magnitude double precision check (impact_magnitude is null or impact_magnitude between 0 and 200),
  source text not null default 'esp32_sensor' check (source = 'esp32_sensor'),
  status text not null default 'unverified' check (status = 'unverified'),
  received_at timestamptz not null,
  check ((latitude is null) = (longitude is null)),
  check ((severity is null) = (event_type is null))
);

create table if not exists public.report_upload_tickets (
  id uuid primary key,
  upload_path text not null unique,
  uploader_hash text not null,
  content_type text not null check (content_type in ('image/jpeg', 'image/png', 'image/webp')),
  expected_size integer not null check (expected_size between 1 and 5242880),
  expires_at timestamptz not null,
  consumed_at timestamptz
);

create table if not exists public.api_rate_limits (
  key text primary key,
  window_started_at timestamptz not null,
  request_count integer not null check (request_count > 0)
);

create index if not exists events_timestamp_id_idx
  on public.events (timestamp desc, id desc);
create index if not exists community_reports_created_at_idx
  on public.community_reports (created_at desc);
create index if not exists device_events_timestamp_idx
  on public.device_events (timestamp desc);

